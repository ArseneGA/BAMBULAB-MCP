// drawText écrit s à (x,y) (coin haut-gauche) avec un facteur d'échelle entier.
func drawText(img *image.RGBA, x, y, scale int, c color.Color, s string) int {
	s = strings.ToUpper(deaccent.Replace(s))
	cx := x
	for _, r := range s {
		if r < 0x20 || r > 0x5F || unicode.IsControl(r) {
			r = '?'
		}
		g := font5x7[r-0x20]
		for col := 0; col < 5; col++ {
			for row := 0; row < 7; row++ {
				if g[col]&(1<<uint(row)) == 0 {
					continue
				}
				for dx := 0; dx < scale; dx++ {
					for dy := 0; dy < scale; dy++ {
						img.Set(cx+col*scale+dx, y+row*scale+dy, c)
					}
				}
			}
		}
		cx += 6 * scale
	}
	return cx
}

func textWidth(s string, scale int) int { return len([]rune(deaccent.Replace(s))) * 6 * scale }
